package installer

// Host files the watch's install writes (docs/ROADMAP.md "Last task before
// production", owner 2026-09-25).
const (
	WatchService   = "linx-watch.service"
	WatchTimer     = "linx-watch.timer"
	watchUnitPath  = "/etc/systemd/system/" + WatchService
	watchTimerPath = "/etc/systemd/system/" + WatchTimer
)

// WatchPlan installs the timer that runs `linx watch`: doctor's own checks
// on a schedule, raising an alert the first time a problem appears and
// clearing it when it goes. Until this existed nothing looked at a running
// server unless somebody typed `linx doctor` — `doctor.Run` had exactly one
// caller, the command itself.
//
// It runs the `linx` already installed at CLIPath rather than a binary of
// its own, because the checks are doctor's and they are in there. So,
// unlike BackupAgentPlan and OpsAgentPlan, there is nothing to copy and no
// reason to skip the plan on a one-binary dev build.
func WatchPlan() Plan {
	return Plan{
		fileStep("Write the watch service", watchUnitPath, []byte(watchServiceUnit), 0o644, 0o755),
		fileStep("Run the checks every five minutes", watchTimerPath, []byte(watchTimerUnit), 0o644, 0o755),
		cmdStep("Tell the system about the timer", "systemctl", "daemon-reload"),
		cmdStep("Turn the timer on", "systemctl", "enable", WatchTimer),
		cmdStep("Start it now", "systemctl", "restart", WatchTimer),
	}
}

const watchServiceUnit = `# Generated by linx setup. Changes are overwritten when setup runs again.
[Unit]
Description=Check a running Linx and raise an alert for anything new
After=docker.service
Requires=docker.service

[Service]
Type=oneshot
ExecStart=` + CLIPath + ` watch
`

// Five minutes, not one: the checks ask DNS, open TLS connections and
// allocate a relay address, so they cost more than the backup agent's
// glance at the database, and a problem that has lasted five minutes is
// still news. Measured on a live server, one run is about 2 s of processor
// and 86 MB for a few seconds, so every five minutes is roughly 0.67% of
// one core and nothing at all in between (docs/RESOURCES.md §3j). The first
// run waits for the stack to come up after a reboot, which would otherwise
// report every service as down.
const watchTimerUnit = `# Generated by linx setup. Changes are overwritten when setup runs again.
[Unit]
Description=Check a running Linx every five minutes

[Timer]
OnBootSec=5min
OnUnitActiveSec=5min
RandomizedDelaySec=30
Unit=` + WatchService + `

[Install]
WantedBy=timers.target
`
